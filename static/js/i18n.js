  let currentLang = 'id';
  let isTranslating = false;

  function initLanguage() {
    try {
      const saved = localStorage.getItem('kertagosa_lang');
      if (saved === 'en' || saved === 'id') {
        currentLang = saved;
      }
    } catch (e) {
      currentLang = 'id';
    }
    window.currentLanguage = currentLang;
    applyLanguage(currentLang, false);
    setupMutationObserver();
  }

  function setLanguage(lang) {
    if (lang !== 'id' && lang !== 'en') return;
    currentLang = lang;
    window.currentLanguage = lang;
    try {
      localStorage.setItem('kertagosa_lang', lang);
    } catch (e) {}

    applyLanguage(lang, true);
  }

  // Translate a single text string from ID to EN
  function translateString(str) {
    if (!str || typeof str !== 'string') return str;
    const trimmed = str.trim();
    if (!trimmed || trimmed.length === 0) return str;

    // Check exact dictionary match
    if (PHRASE_DICTIONARY[trimmed]) {
      return str.replace(trimmed, PHRASE_DICTIONARY[trimmed]);
    }

    // Check case-insensitive dictionary match
    const lower = trimmed.toLowerCase();
    for (const [k, v] of Object.entries(PHRASE_DICTIONARY)) {
      if (k.toLowerCase() === lower) {
        return str.replace(trimmed, v);
      }
    }

    // Apply regex pattern rules
    let result = str;
    for (const rule of SUBSTRING_RULES) {
      if (rule.from.test(result)) {
        result = result.replace(rule.from, rule.to);
      }
    }

    return result;
  }

  // Deep recursive DOM tree translator
  function translateDom(rootNode, lang) {
    if (!rootNode || isTranslating) return;
    isTranslating = true;

    try {
      // TreeWalker to visit all text nodes
      const walker = document.createTreeWalker(
        rootNode,
        NodeFilter.SHOW_TEXT,
        {
          acceptNode: function (node) {
            if (!node || !node.nodeValue) return NodeFilter.FILTER_REJECT;
            const parent = node.parentElement;
            if (!parent) return NodeFilter.FILTER_REJECT;
            const tag = parent.tagName.toLowerCase();
            if (tag === 'script' || tag === 'style' || tag === 'noscript' || tag === 'svg' || tag === 'path') {
              return NodeFilter.FILTER_REJECT;
            }
            if (parent.closest('.no-translate') || parent.closest('#inline-edit-value')) {
              return NodeFilter.FILTER_REJECT;
            }
            if (node.nodeValue.trim().length === 0) {
              return NodeFilter.FILTER_REJECT;
            }
            return NodeFilter.FILTER_ACCEPT;
          }
        }
      );

      let textNode;
      while ((textNode = walker.nextNode())) {
        if (lang === 'en') {
          if (textNode._i18nOrig === undefined) {
            textNode._i18nOrig = textNode.nodeValue;
          }
          const translated = translateString(textNode._i18nOrig);
          if (translated !== textNode.nodeValue) {
            textNode.nodeValue = translated;
          }
        } else {
          if (textNode._i18nOrig !== undefined) {
            textNode.nodeValue = textNode._i18nOrig;
          }
        }
      }

      // Translate attributes: placeholder, title, aria-label
      const elementsWithAttrs = rootNode.querySelectorAll ? rootNode.querySelectorAll('input, textarea, button, a, [title], [aria-label]') : [];
      elementsWithAttrs.forEach(el => {
        // Placeholder
        if (el.hasAttribute('placeholder')) {
          if (lang === 'en') {
            if (el._i18nOrigPlaceholder === undefined) {
              el._i18nOrigPlaceholder = el.getAttribute('placeholder');
            }
            el.setAttribute('placeholder', translateString(el._i18nOrigPlaceholder));
          } else if (el._i18nOrigPlaceholder !== undefined) {
            el.setAttribute('placeholder', el._i18nOrigPlaceholder);
          }
        }

        // Title
        if (el.hasAttribute('title')) {
          if (lang === 'en') {
            if (el._i18nOrigTitle === undefined) {
              el._i18nOrigTitle = el.getAttribute('title');
            }
            el.setAttribute('title', translateString(el._i18nOrigTitle));
          } else if (el._i18nOrigTitle !== undefined) {
            el.setAttribute('title', el._i18nOrigTitle);
          }
        }

        // Aria-label
        if (el.hasAttribute('aria-label')) {
          if (lang === 'en') {
            if (el._i18nOrigAriaLabel === undefined) {
              el._i18nOrigAriaLabel = el.getAttribute('aria-label');
            }
            el.setAttribute('aria-label', translateString(el._i18nOrigAriaLabel));
          } else if (el._i18nOrigAriaLabel !== undefined) {
            el.setAttribute('aria-label', el._i18nOrigAriaLabel);
          }
        }
      });

    } finally {
      isTranslating = false;
    }
  }

  function applyLanguage(lang, showToastNotification) {
    const dict = I18N_TRANSLATIONS[lang] || I18N_TRANSLATIONS.id;

    // 1. Set document language attribute
    document.documentElement.lang = lang;

    // 2. Update toggle buttons appearance
    const btnId = document.getElementById('btn-lang-id');
    const btnEn = document.getElementById('btn-lang-en');
    const mobBtnId = document.getElementById('mob-btn-lang-id');
    const mobBtnEn = document.getElementById('mob-btn-lang-en');

    const activeClass = 'bg-[#0B3B24] text-white shadow-xs';
    const inactiveClass = 'text-slate-600 hover:text-slate-900';

    if (btnId && btnEn) {
      if (lang === 'en') {
        btnId.className = 'px-2 py-0.5 rounded-md text-[11px] font-extrabold transition-all ' + inactiveClass;
        btnEn.className = 'px-2 py-0.5 rounded-md text-[11px] font-extrabold transition-all ' + activeClass;
      } else {
        btnId.className = 'px-2 py-0.5 rounded-md text-[11px] font-extrabold transition-all ' + activeClass;
        btnEn.className = 'px-2 py-0.5 rounded-md text-[11px] font-extrabold transition-all ' + inactiveClass;
      }
    }

    if (mobBtnId && mobBtnEn) {
      if (lang === 'en') {
        mobBtnId.className = 'px-3 py-1 rounded-md text-xs font-bold transition-all ' + inactiveClass;
        mobBtnEn.className = 'px-3 py-1 rounded-md text-xs font-bold transition-all ' + activeClass;
      } else {
        mobBtnId.className = 'px-3 py-1 rounded-md text-xs font-bold transition-all ' + activeClass;
        mobBtnEn.className = 'px-3 py-1 rounded-md text-xs font-bold transition-all ' + inactiveClass;
      }
    }

    // 3. Fast exact mapping for elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key && dict[key] !== undefined) {
        if (!el.hasAttribute('data-i18n-orig')) {
          el.setAttribute('data-i18n-orig', el.textContent.trim());
        }
        el.textContent = dict[key];
      }
    });

    // 4. Translate all elements with data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (key && dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    // 5. Deep full-page text node translation
    translateDom(document.body, lang);

    // 6. Refresh lucide icons if loaded
    if (window.lucide && typeof window.lucide.createIcons === 'function') {
      window.lucide.createIcons();
    }

    // 7. Dispatch language changed event
    try {
      window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: lang } }));
    } catch (_) {}

    if (showToastNotification) {
      showLangToast(lang === 'en' ? 'Switched to English' : 'Bahasa Indonesia aktif');
    }
  }

  function setupMutationObserver() {
    if (!window.MutationObserver) return;
    let debounceTimer = null;

    const observer = new MutationObserver((mutations) => {
      if (currentLang !== 'en') return;

      let hasRelevantChange = false;
      for (const m of mutations) {
        if (m.type === 'childList' && m.addedNodes.length > 0) {
          for (const node of m.addedNodes) {
            if (node.nodeType === 1 && !node.closest?.('.no-translate') && !node.id?.includes('toast')) {
              hasRelevantChange = true;
              break;
            }
          }
        }
        if (hasRelevantChange) break;
      }

      if (hasRelevantChange) {
        clearTimeout(debounceTimer);
        debounceTimer = setTimeout(() => {
          if (currentLang === 'en') {
            translateDom(document.body, 'en');
          }
        }, 80);
      }
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true
    });
  }

  function showLangToast(msg) {
    let toast = document.getElementById('kertagosa-lang-toast');
    if (!toast) {
      toast = document.createElement('div');
      toast.id = 'kertagosa-lang-toast';
      toast.className = 'fixed top-16 right-5 z-[9999] px-4 py-2.5 rounded-xl bg-slate-900/95 text-white text-xs font-bold shadow-2xl border border-slate-700 backdrop-blur-sm transition-all duration-300 pointer-events-none transform translate-y-0 opacity-100 flex items-center gap-2 no-translate';
      document.body.appendChild(toast);
    }
    toast.innerHTML = `<span class="w-2 h-2 rounded-full bg-emerald-400 animate-ping"></span> <span>${msg}</span>`;
    toast.classList.remove('opacity-0', 'pointer-events-none');
    toast.classList.add('opacity-100');

    clearTimeout(window._langToastTimer);
    window._langToastTimer = setTimeout(() => {
      toast.classList.remove('opacity-100');
      toast.classList.add('opacity-0', 'pointer-events-none');
    }, 2400);
  }

